const {Router} = require('express');

const {
  SYSTEM_ENTITIES,
  CRUD_PERMISSIONS,
  TRIAGE_ENGINE_PERMISSIONS,
} = require('../../constants/aclConstants');

const {TriageEngineController} = require('../../controllers');

const {
  validatorMiddleware,
  catchAsyncMiddleware,
  aclAccessMiddleware,
} = require('../../middleware');

const {triageEngineSchema} = require('../../schemas');

const router = Router();

const ENTITY = SYSTEM_ENTITIES.triageEngine.value;

// GET /triage-engine/stats — active flag counts (red & yellow) plus the GREEN
// flag count over a date window (default last 30 days, overridable via
// startDate/endDate). Admins, nurses and case managers (triageEngine.view
// permission); scoped to the caller's active organization.
router.get(
  '/stats',
  validatorMiddleware({
    validateFunction: triageEngineSchema.validateGetStatsQuery,
    reqProperty: 'query',
  }),
  aclAccessMiddleware({
    entityToCheck: ENTITY,
    permissionKey: CRUD_PERMISSIONS.VIEW,
  }),
  catchAsyncMiddleware(TriageEngineController.getActiveFlagStats)
);

// GET /triage-engine/alerts — paginated submission flags (all colours), newest
// first, for the "Alerts Generated By System" panel. Admin-only
// (triageEngine.viewAlerts); scoped to the caller's active organization.
router.get(
  '/alerts',
  validatorMiddleware({
    validateFunction: triageEngineSchema.validateGetAlertsQuery,
    reqProperty: 'query',
  }),
  aclAccessMiddleware({
    entityToCheck: ENTITY,
    permissionKey: TRIAGE_ENGINE_PERMISSIONS.VIEW_ALERTS,
  }),
  catchAsyncMiddleware(TriageEngineController.getRecentAlerts)
);

module.exports = router;
