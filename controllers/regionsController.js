const {PRISMA_DUPLICATION_ERROR_CODE} = require('../constants/errorsConstants');
const {REGIONS_SORT_FIELDS} = require('../constants/regionsConstants');

const {
  GeneralErrorsFactories,
  RegionsErrorsFactories,
  RegionsResponsesFactories,
  GeneralResponsesFactories,
} = require('../factories');

const {
  RegionsServices,
  CountiesServices,
  NursesServices,
} = require('../services');

const {computeCollectionDiff} = require('../utils/collectionDiffUtils');

const {
  getListParams,
  buildOrderByClause,
  withIdTieBreaker,
  generateRegionCode,
  filterUndefined,
  safeConcat,
  parseBoolean,
} = require('../utils/general');
const {wrapWithPrismaTransaction} = require('../utils/prismaTransactionUtils');

module.exports = class RegionsController {
  /**
   * List all regions in organization
   * GET /regions
   */
  static async listRegions(req, res, next) {
    // Query params are already validated by route middleware
    // getListParams extracts all query params: page, limit, skip, search, date, sortBy, sortDir
    const {page, limit, skip, search, sortBy, sortDir} = getListParams({req});
    const {isActive, archiveFilter} = req.query;

    // Build sort object for Prisma
    const orderBy = buildOrderByClause({
      sortBy,
      sortDir,
      sortFields: REGIONS_SORT_FIELDS,
    });

    const {
      success,
      docs: regions,
      error,
      count,
    } = await RegionsServices.listRegions({
      isActive: parseBoolean({val: isActive}),
      archiveFilter,
      search,
      skip,
      take: limit,
      sort: withIdTieBreaker({orderBy}),
    });

    if (!success || error) {
      throw RegionsErrorsFactories.failedToFetchRegionsErr();
    }

    return RegionsResponsesFactories.regionsListRetrieved({
      regions,
      meta: {
        page: parseInt(page, 10),
        limit: parseInt(limit, 10),
        count,
        totalPages: Math.ceil(count / limit),
      },
    });
  }

  /**
   * Get regions summary with counts for nurses, counties, patients, case managers
   * GET /regions/summary
   */
  static async getRegionsSummary(req, res, next) {
    const {
      success,
      docs: regions,
      error,
    } = await RegionsServices.getRegionsWithSummaryCounts();

    if (!success || error) {
      throw RegionsErrorsFactories.failedToFetchRegionsSummaryErr();
    }

    return RegionsResponsesFactories.regionsSummaryRetrieved({
      regionsSummary: regions,
    });
  }

  /**
   * Get a single region by ID
   * GET /regions/:id
   */
  static async getRegion(req, res, next) {
    const {id} = req.params;

    const {success, doc: region} = await RegionsServices.getRegionById({id});

    if (!success || !region) {
      throw GeneralErrorsFactories.notFoundErr({
        customMessage: 'Region not found',
      });
    }

    return GeneralResponsesFactories.dataRetrievedSuccessfully({
      data: region,
      key: 'region',
    });
  }

  /**
   * Create a new region
   * POST /regions
   * Accepts county FIPS codes — creates counties alongside the region in one atomic operation
   */
  static async createRegion(req, res, next) {
    const {
      name,
      code: manualCode,
      isActive = true,
      counties = [],
      primaryNurseProfileIds = [],
      secondaryNurseProfileIds = [],
    } = req.body;
    const token = req.extra.jwtToken;
    const organizationId = token.user.currentActiveOrganization.organizationId;

    const {valid: nursesValid, reason: invalidNurseReason} =
      await NursesServices.validateNurses({
        ids: safeConcat({
          originalArray: primaryNurseProfileIds,
          newArray: secondaryNurseProfileIds,
        }),
      });

    if (!nursesValid) {
      throw RegionsErrorsFactories.invalidNurseForRegionErr({
        reason: invalidNurseReason,
      });
    }

    // Auto-generate code from name if not provided manually
    const codeWasAutoGenerated = !manualCode;
    const code = manualCode || generateRegionCode({name});

    // Check if region code already exists in organization
    const {doc: existingRegion} = await RegionsServices.getRegionByCode({
      code,
      organizationId,
    });

    if (existingRegion) {
      throw RegionsErrorsFactories.regionAlreadyExistsErr(
        codeWasAutoGenerated ? {name} : {code}
      );
    }

    const fipsCodes = counties.map((county) => county.fipsCode);

    // Reject counties the organization already has in another region
    if (fipsCodes.length > 0) {
      const conflictingNames = await CountiesServices.findConflictingCounties({
        fipsCodes,
        organizationId,
      });

      if (conflictingNames.length > 0) {
        throw RegionsErrorsFactories.countyNameAlreadyExistsErr({
          countyNames: conflictingNames,
        });
      }
    }

    // Create region and counties in single transaction
    const createdRegion = await wrapWithPrismaTransaction({
      fn: async (tx) => {
        // Step 1: Create region
        const {
          success: createSuccess,
          doc: region,
          error: createError,
        } = await RegionsServices.createRegion({
          name,
          code,
          organizationId,
          isActive,
          tx,
        });

        if (!createSuccess || createError) {
          throw RegionsErrorsFactories.failedToCreateRegionErr();
        }

        // Step 2: Assign primary/secondary nurses to the region (NurseRegion roster)
        const {success: assignSuccess, error: assignError} =
          await RegionsServices.assignNursesToRegion({
            regionId: region.id,
            primaryNurseProfileIds,
            secondaryNurseProfileIds,
            organizationId,
            tx,
          });

        if (!assignSuccess || assignError) {
          throw RegionsErrorsFactories.failedToCreateRegionErr();
        }

        // Step 3: Create counties if provided
        if (fipsCodes.length > 0) {
          const {
            success: countiesSuccess,
            docs: createdCounties,
            error: countiesError,
          } = await CountiesServices.bulkCreateCounties({
            fipsCodes,
            regionId: region.id,
            organizationId,
            tx,
          });

          if (!countiesSuccess || countiesError) {
            // Detect Prisma unique constraint violation
            const isPrismaUniqueError =
              countiesError?.code === PRISMA_DUPLICATION_ERROR_CODE ||
              countiesError?.message?.includes('Unique constraint');

            if (isPrismaUniqueError) {
              throw RegionsErrorsFactories.countyNameAlreadyExistsErr();
            }

            throw GeneralErrorsFactories.internalErr({
              customMessage: 'Failed to create counties',
            });
          }

          // Attach counties to the returned region object
          region.counties = createdCounties;
        }

        return region;
      },
    });

    return GeneralResponsesFactories.dataSavedSuccessfully({
      data: createdRegion,
      key: 'region',
    });
  }

  /**
   * Update a region
   * PATCH /regions/:id
   * Accepts counties as {fipsCode} or {id} — computes diff to create new / hard-delete removed counties
   */
  static async updateRegion(req, res, next) {
    const {id} = req.params;

    const {
      name,
      code,
      isActive,
      counties,
      primaryNurseProfileIds,
      secondaryNurseProfileIds,
    } = req.body;
    const token = req.extra.jwtToken;
    const organizationId = token.user.currentActiveOrganization.organizationId;

    const [
      {valid: nursesValid, reason: invalidNurseReason},
      {success, doc: region},
    ] = await Promise.all([
      NursesServices.validateNurses({
        ids: safeConcat({
          originalArray: primaryNurseProfileIds || [],
          newArray: secondaryNurseProfileIds || [],
        }),
      }),
      RegionsServices.getRegionById({id}),
    ]);

    if (!nursesValid)
      throw RegionsErrorsFactories.invalidNurseForRegionErr({
        reason: invalidNurseReason,
      });

    if (!success || !region) {
      throw GeneralErrorsFactories.notFoundErr({
        customMessage: 'Region not found',
      });
    }

    // If code is being changed, check for duplicates
    if (code && code !== region.code) {
      const {doc: existingRegion} = await RegionsServices.getRegionByCode({
        code,
        organizationId,
      });

      if (existingRegion) {
        throw RegionsErrorsFactories.regionAlreadyExistsErr({code});
      }
    }

    // Build update data without spread operator.
    const updateData = filterUndefined({
      obj: {
        name,
        code,
        isActive,
      },
    });
    const hasRegionFieldUpdates = Object.keys(updateData).length > 0;

    // Update region and manage counties in single transaction
    const updatedRegion = await wrapWithPrismaTransaction({
      fn: async (tx) => {
        let updated = region;

        // Step 1: Update region details only if there are field changes
        if (hasRegionFieldUpdates) {
          const {
            doc: updatedDoc,
            error: updateError,
            success: updateSuccess,
          } = await RegionsServices.updateRegion({
            id,
            updateData,
            tx,
          });

          if (!updateSuccess || updateError) {
            throw RegionsErrorsFactories.failedToUpdateRegionErr();
          }

          updated = updatedDoc;
        }

        // Step 2: Manage counties if provided
        if (counties !== undefined) {
          const currentCounties = region.counties || [];

          const keptIds = new Set(
            counties.map((county) => county.id).filter(Boolean)
          );

          const currentIds = new Set(
            currentCounties.map((county) => county.id)
          );

          // An id from elsewhere keeps nothing, and would leave the region empty.
          if (
            Array.from(keptIds).some((countyId) => !currentIds.has(countyId))
          ) {
            throw GeneralErrorsFactories.notFoundErr({
              customMessage: 'County not found in this region',
            });
          }

          const {itemsToRemove: notPickedByCode, valuesToCreate} =
            computeCollectionDiff({
              currentItems: currentCounties,
              desiredValues: counties
                .map((county) => county.fipsCode)
                .filter(Boolean),
              key: 'fipsCode',
            });

          // A county sent by id stays, which is how one without a FIPS code survives.
          const itemsToRemove = notPickedByCode.filter(
            (county) => !keptIds.has(county.id)
          );

          const itemsToKeep = currentCounties.filter(
            (county) => !itemsToRemove.includes(county)
          );

          // Bulk hard-delete removed counties (will fail if any have patients — FK constraint)
          if (itemsToRemove.length > 0) {
            const {success: deleteSuccess, error: deleteError} =
              await CountiesServices.bulkDeleteCounties({
                countyIds: itemsToRemove.map((county) => county.id),
                tx,
              });

            if (!deleteSuccess || deleteError) {
              throw GeneralErrorsFactories.internalErr({
                customMessage: `Cannot remove counties — they may have patients assigned`,
              });
            }
          }

          // Create new counties in bulk
          let createdCounties = [];
          if (valuesToCreate.length > 0) {
            // Reject counties the organization already has in another region
            const conflictingNames =
              await CountiesServices.findConflictingCounties({
                fipsCodes: valuesToCreate,
                organizationId,
                tx,
              });

            if (conflictingNames.length > 0) {
              throw RegionsErrorsFactories.countyNameAlreadyExistsErr({
                countyNames: conflictingNames,
              });
            }

            const {
              success: bulkSuccess,
              docs: bulkCreated,
              error: bulkError,
            } = await CountiesServices.bulkCreateCounties({
              fipsCodes: valuesToCreate,
              regionId: id,
              organizationId,
              tx,
            });

            if (!bulkSuccess || bulkError) {
              // Detect Prisma unique constraint violation
              const isPrismaUniqueError =
                bulkError?.code === PRISMA_DUPLICATION_ERROR_CODE ||
                bulkError?.message?.includes('Unique constraint');

              if (isPrismaUniqueError) {
                throw RegionsErrorsFactories.countyNameAlreadyExistsErr();
              }

              throw GeneralErrorsFactories.internalErr({
                customMessage: 'Failed to create counties',
              });
            }

            createdCounties = bulkCreated;
          }

          // Build final counties list: kept + newly created
          updated.counties = safeConcat({
            originalArray: itemsToKeep,
            newArray: createdCounties,
          });
        }

        // Step 3: Sync the region's DEFAULT primary/secondary nurse roster
        // (RegionDefaultNurse). An undefined list is left untouched (PATCH); an empty
        // array clears it. This roster is INDEPENDENT of a nurse's own region
        // coverage (NurseRegion), so it deliberately does NOT cascade to
        // patient assignments — patient coverage follows the nurse-owned roster
        // only, enforced by the nurse-side edit flow (PREVENT-411).
        const {success: assignSuccess, error: assignError} =
          await RegionsServices.assignNursesToRegion({
            regionId: id,
            primaryNurseProfileIds,
            secondaryNurseProfileIds,
            organizationId,
            tx,
          });

        if (!assignSuccess || assignError) {
          throw RegionsErrorsFactories.failedToUpdateRegionErr();
        }

        return updated;
      },
    });

    return GeneralResponsesFactories.dataUpdatedSuccessfully({
      data: updatedRegion,
      key: 'region',
    });
  }

  /**
   * Delete (soft-delete) a region
   * DELETE /regions/:id
   */
  static async deleteRegion(req, res, next) {
    const {id} = req.params;

    // Get region
    const {success: getRegionSuccess, doc: region} =
      await RegionsServices.getRegionById({id});

    if (!getRegionSuccess || !region) {
      throw GeneralErrorsFactories.notFoundErr({
        customMessage: 'Region not found',
      });
    }

    // Check if region has nurses assigned
    const {
      success: getNursesSuccess,
      docs: nursesInRegion,
      error: getNursesError,
    } = await RegionsServices.getNursesInRegion({
      regionId: id,
    });

    if (!getNursesSuccess || getNursesError) {
      throw RegionsErrorsFactories.failedToFetchNursesInRegionErr();
    }

    if (nursesInRegion.length > 0) {
      throw RegionsErrorsFactories.regionHasNursesAssignedErr({
        nurseCount: nursesInRegion.length,
      });
    }

    // Check if region has patients assigned
    const {
      success: getPatientsSuccess,
      docs: patientsInRegion,
      error: getPatientsError,
    } = await RegionsServices.getPatientsInRegion({
      regionId: id,
    });

    if (!getPatientsSuccess || getPatientsError) {
      throw RegionsErrorsFactories.failedToDeleteRegionErr();
    }

    if (patientsInRegion.length > 0) {
      throw RegionsErrorsFactories.regionHasPatientsAssignedErr({
        patientCount: patientsInRegion.length,
      });
    }

    // Check if region has case managers assigned
    const {
      success: getCaseManagersSuccess,
      docs: caseManagersInRegion,
      error: getCaseManagersError,
    } = await RegionsServices.getCaseManagersInRegion({
      regionId: id,
    });

    if (!getCaseManagersSuccess || getCaseManagersError) {
      throw RegionsErrorsFactories.failedToDeleteRegionErr();
    }

    if (caseManagersInRegion.length > 0) {
      throw RegionsErrorsFactories.regionHasCaseManagersAssignedErr({
        caseManagerCount: caseManagersInRegion.length,
      });
    }

    const {
      success: deleteRegionSuccess,
      doc: deletedRegion,
      error,
    } = await RegionsServices.deleteRegion({id});

    if (!deleteRegionSuccess || error) {
      throw RegionsErrorsFactories.failedToDeleteRegionErr();
    }

    return GeneralResponsesFactories.dataDeletedSuccessfully({
      data: deletedRegion,
      key: 'region',
    });
  }

  /**
   * Get nurses assigned to a region
   * GET /regions/:id/nurses
   */
  static async getRegionNurses(req, res, next) {
    const {id} = req.params;

    // Verify region exists
    const {success: getRegionSuccess, doc: region} =
      await RegionsServices.getRegionById({id});

    if (!getRegionSuccess || !region) {
      throw GeneralErrorsFactories.notFoundErr({
        customMessage: 'Region not found',
      });
    }

    const {
      success: getNursesSuccess,
      docs: nurseAssignments,
      error: getNursesError,
    } = await RegionsServices.getNursesInRegion({
      regionId: id,
    });

    if (!getNursesSuccess || getNursesError) {
      throw RegionsErrorsFactories.failedToFetchNursesInRegionErr();
    }

    // Formatting is handled inside the response factory
    return RegionsResponsesFactories.regionNursesRetrieved({
      region,
      nurseAssignments,
    });
  }
};
